# frozen_string_literal: true

module Brutal
  # The test a manifest describes, as Ruby source code, in two forms with the
  # same lines: one that records the observed values, and the test file,
  # which checks them.
  #
  # `%{name}` in the subject is replaced by each fragment of the context
  # `name`, for every combination of the contexts, and `%{subject}` in an
  # actual by `actual`, the local variable that holds the subject's value.
  # Nothing else is interpreted: a `%` is a `%`.
  class Program
    # The first line of every test file, without the name of the manifest.
    MARK = "# Generated by brutal from "

    PLACEHOLDER = /%\{([A-Za-z_][A-Za-z0-9_]*)\}/
    SEPARATOR = "# #{"-" * 78}".freeze
    SECTIONS = %i[header before after footer].freeze

    private_constant :PLACEHOLDER, :SEPARATOR, :SECTIONS

    # @return [Array<Hash{String => String}>] the fragment of each context, for each example
    attr_reader :cases

    # @param manifest [Brutal::Manifest]
    # @raise [Brutal::Error] when a placeholder or a context is unknown or
    #   unused, or a section, a subject or an actual is not complete code on
    #   its own
    def initialize(manifest)
      @manifest = manifest
      check
      names = manifest.contexts.keys
      first, *rest = manifest.contexts.values
      @cases = first.product(*rest).map { |fragments| names.zip(fragments).to_h.freeze }.freeze
      parse
      freeze
    end

    # @return [Integer] the number of observed values: one per example and actual
    def size
      cases.size * @manifest.actuals.size
    end

    # The program that records the observed values: `$__brutal__` receives
    # `enter` with the index of each example (`cases.size` for the footer),
    # and `observe` with each observed value.
    #
    # @return [String]
    def record
      source(separator: ->(index) { "$__brutal__.enter(#{index})" }, assertion: ->(_index) { "$__brutal__.observe((" })
    end

    # The test file: each observed value must be `eql?` to its literal.
    #
    # @param literals [Array<String>] the literal of each observed value, in order
    # @return [String]
    def test(literals)
      assertion = ->(index) { "::Kernel.raise #{label(index).dump} unless (#{literals.fetch(index)}).eql?((" }
      source(separator: ->(_index) { SEPARATOR }, assertion:)
    end

    # Where an observed value comes from, for messages.
    #
    # @param index [Integer] the index of an observed value
    # @return [String] the fragments of its example, and its actual
    def label(index)
      example, actual = index.divmod(@manifest.actuals.size)
      "#{phase(example)}: #{observation(@manifest.actuals.fetch(actual))}"
    end

    # Names a part of the program, for messages.
    #
    # @param index [Integer, nil] the index of an example, nil for the header, `cases.size` for the footer
    # @return [String]
    def phase(index)
      return "the header" if index.nil?
      return "the footer" if index == cases.size

      cases.fetch(index).map { |name, fragment| "#{name} = #{fragment}" }.join(", ")
    end

    private

    # Refuses a placeholder without context, a context without placeholder,
    # and a placeholder where brutal does not replace it.
    def check
      names = @manifest.contexts.keys
      used = placeholders(@manifest.subject)
      refuse(used - names, "the subject uses %{NAME}, which is not a context")
      refuse(names - used, "the context NAME is not used in the subject")
      refuse(@manifest.actuals.flat_map { |actual| placeholders(actual) } - ["subject"],
             "an actual can only use %{subject}, not %{NAME}")
      SECTIONS.each do |section|
        refuse(placeholders(@manifest.public_send(section).to_s), "the #{section} uses %{NAME}, which is not replaced")
      end
    end

    # Refuses code that is not complete on its own: each part must parse
    # alone, so that no part can change how the others parse, or hide a
    # check.
    def parse
      SECTIONS.each { |section| alone(@manifest.public_send(section), "the #{section}") }
      cases.each_with_index { |fragments, index| alone(subject(fragments), "the subject, for #{phase(index)},") }
      @manifest.actuals.each { |actual| alone(observation(actual), "the actual #{actual.dump}") }
    end

    # Compiles a part of the code alone, warnings off: nothing runs. The part
    # starts on the third line, as the header does in the test file, so that a
    # magic comment of the first line (`# encoding:`) is ignored as it is
    # there; the line numbers of the part are kept.
    def alone(code, part)
      return if code.nil?
      raise Error, "#{part} holds an end of file (__END__, NUL, ^D or ^Z)" if code.match?(/^__END__\r?$|[\0\x04\x1a]/)

      verbose = $VERBOSE
      $VERBOSE = nil
      ::RubyVM::InstructionSequence.compile("\n\n#{code}", "<compiled>", "<compiled>", -1)
    rescue ::SyntaxError => e
      raise Error, "#{part} is not complete code on its own: #{e.message.sub("<compiled>:", "line ")}"
    ensure
      $VERBOSE = verbose unless verbose.nil?
    end

    # Raises the message, with the first name for NAME, if there is one.
    def refuse(names, message)
      raise Error, message.sub("NAME", names.first) unless names.empty?
    end

    # The names of the placeholders of a template.
    def placeholders(template)
      template.scan(PLACEHOLDER).flatten.uniq
    end

    # The program; `separator` and `assertion` give the lines that differ
    # between its two forms, from the index of an example and of an observed
    # value.
    def source(separator:, assertion:)
      [
        "#{MARK}#{::File.basename(@manifest.path)}: edit the manifest, then run brutal again.", "",
        *([@manifest.header, ""] if @manifest.header),
        *cases.each_with_index.flat_map { |fragments, index| example(fragments, index, separator, assertion) },
        *([separator.call(cases.size), "", @manifest.footer, ""] if @manifest.footer)
      ].join("\n")
    end

    # The lines of one example.
    def example(fragments, index, separator, assertion)
      [
        separator.call(index), "",
        *([@manifest.before, ""] if @manifest.before),
        "actual = begin", nest(subject(fragments)), "end", "",
        *assertions(index, assertion),
        *(["", @manifest.after] if @manifest.after),
        ""
      ]
    end

    # The lines of the assertions of one example.
    def assertions(index, assertion)
      @manifest.actuals.each_with_index.flat_map do |actual, position|
        [assertion.call((index * @manifest.actuals.size) + position), nest(observation(actual)), "))"]
      end
    end

    # The subject, with the fragment of each context for its placeholder.
    def subject(fragments)
      @manifest.subject.gsub(PLACEHOLDER) { fragments.fetch(::Regexp.last_match(1)) }
    end

    # An actual, with `actual` for `%{subject}`.
    def observation(actual)
      actual.gsub(PLACEHOLDER, "actual")
    end

    # Indents a code fragment of one line. A fragment of several lines is
    # left as written: indenting it would change a multi-line string or a
    # heredoc.
    def nest(code)
      code.include?("\n") ? code : "  #{code}"
    end
  end
end
