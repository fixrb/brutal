# frozen_string_literal: true

require_relative File.join("support", "coverage")
require_relative File.join("..", "lib", "brutal")
require_relative File.join("support", "project")

# Edge cases found by mutation testing and by review: each check kills a
# change of the code that the rest of the suite let through.

valid = "subject: '%{a} + 1'\ncontexts: {a: [1]}\nactuals: ['%{subject}']\n"
executable = File.join(__dir__, "..", "bin", "brutal")
environment = manifest("subject: '[ARGV, $0 == __FILE__, gets, %{n}]'\ncontexts: {n: [1]}\nactuals: ['%{subject}']\n")

# A symbolic link to a directory elsewhere is not searched.
elsewhere = project("y_brutal.yaml" => valid)
linking = project("x_brutal.yaml" => valid)
File.symlink(elsewhere, File.join(linking, "elsewhere"))
raise unless brutal(linking) == [0, "", ""]
raise if File.exist?(File.join(elsewhere, "test_y.rb"))

# A test file brutal cannot replace is refused before the code runs.
hand = project("x_brutal.yaml" => "header: File.write(File.join(__dir__, 'ran'), '')\n#{valid}",
               "test_x.rb"     => "# Mine.\n")
raise unless brutal(hand)[0] == 1
raise if File.exist?(File.join(hand, "ran"))

# The command writes a test file only once ruby has run it and it passed.
differs = project("x_brutal.yaml" => "subject: '[defined?(Brutal), %{n}]'\ncontexts: {n: [1]}\n" \
                                     "actuals: ['%{subject}']\n")
status, _, err = brutal(differs)
raise unless status == 1 && err.include?(": the test file fails when ruby runs it: ")
raise if File.exist?(File.join(differs, "test_x.rb"))

# A replaced file keeps its permissions, never its setuid, setgid or sticky
# bits.
special = File.join(project({}), "test_special.rb")
source = "# Generated by brutal from x_brutal.yaml: edit the manifest, then run brutal again.\n"
Brutal::Output.write(special, source)
File.chmod(0o2750, special)
Brutal::Output.write(special, "#{source}# changed\n")
raise unless File.stat(special).mode & 0o7777 == 0o750

# An interruption while the file is written or run leaves no temporary file.
interrupting = false
File.prepend(Module.new { define_method(:write) { |*text| interrupting ? raise(Interrupt) : super(*text) } })
begin
  interrupting = true
  Brutal::Output.write(special, "#{source}# written\n")
  raise "expected Interrupt"
rescue Interrupt
  raise unless Dir.children(File.dirname(special)) == ["test_special.rb"]
ensure
  interrupting = false
end
begin
  Brutal::Output.write(special, "#{source}# run\n") { |_temporary| raise Interrupt }
  raise "expected Interrupt"
rescue Interrupt
  raise unless Dir.children(File.dirname(special)) == ["test_special.rb"]
end

# An __END__ line ended by CR LF is refused too.
crlf = manifest("before: \"__END__\\r\\nx\"\nsubject: '1 + %{n}'\ncontexts: {n: [0]}\nactuals: ['%{subject}']\n")
raise unless failure(crlf) == "the before holds an end of file (__END__, NUL, ^D or ^Z)"

# A part compiled alone gives no warning.
stderr = $stderr
$stderr = StringIO.new
begin
  Brutal.generate(manifest("subject: '%{n}'\ncontexts: {n: [5]}\nactuals: ['%{subject} -1']\n"))
  warnings = $stderr.string
ensure
  $stderr = stderr
end
raise if warnings.include?("<compiled>")

# The first unknown placeholder is named.
unknown = manifest("subject: '%{a} + %{b} + %{c}'\ncontexts: {a: [1]}\nactuals: [x]\n")
raise unless failure(unknown) == "the subject uses %{b}, which is not a context"

# The code reads nothing from the standard input, in brutal's child and in ruby.
reader, writer = IO.pipe
writer.puts("typed")
writer.close
saved = $stdin.dup
begin
  $stdin.reopen(reader)
  Brutal.write(Brutal.generate(environment))
ensure
  $stdin.reopen(saved)
end

# The recorder's state is read even if the code redefines instance_variable_get on it.
spoofed = manifest("before: def $__brutal__.instance_variable_get(*) = raise('spoofed')\n#{valid}")
raise unless failure(spoofed).nil? && Brutal.generate(spoofed).source.include?("(2).eql?((")

# What the test file prints when ruby runs it is discarded.
noisy = project("x_brutal.yaml" => "header: $stdout.puts(:ran)\n#{valid}")
raise unless IO.popen([RbConfig.ruby, executable, noisy], &:read) == "ran\n"

# Interrupted, Runner.run kills the test file at once rather than waiting for it.
directory = project("test_slow.rb" => "File.write(File.join(__dir__, 'started'), '')\nsleep 30\n")
main = Thread.current
watcher = Thread.new do
  sleep 0.05 until File.exist?(File.join(directory, "started"))
  main.raise(Interrupt)
end
started = Process.clock_gettime(Process::CLOCK_MONOTONIC)
begin
  Brutal::Runner.run(File.join(directory, "test_slow.rb"))
  raise "expected Interrupt"
rescue Interrupt
  watcher.join
end
raise unless Process.clock_gettime(Process::CLOCK_MONOTONIC) - started < 10

# What the test file writes on its standard error comes back as valid UTF-8.
File.write(File.join(directory, "test_bytes.rb"), "$stderr.write(\"caf\\xC3\\xA9 \\xFF\\n\".b)\nexit 1\n")
bytes = Brutal::Runner.run(File.join(directory, "test_bytes.rb"))
raise unless bytes.encoding == Encoding::UTF_8 && bytes == "caf\u00E9 \uFFFD (exit status 1)"

# Read as bytes, whatever the default internal encoding.
File.write(File.join(directory, "test_fail.rb"), "raise 'broken'\n")
verbose = $VERBOSE
internal = Encoding.default_internal
begin
  $VERBOSE = nil
  Encoding.default_internal = Encoding::UTF_16LE
  failing = Brutal::Runner.run(File.join(directory, "test_fail.rb"))
ensure
  Encoding.default_internal = internal
  $VERBOSE = verbose
end
raise unless failing.include?("broken (RuntimeError)")

# Program#test refuses a list of literals of the wrong size.
short = begin
  Brutal::Program.new(Brutal::Manifest.read(manifest(valid))).test([])
rescue IndexError
  nil
end
raise if short

# Interrupted, the command ends by the signal without a backtrace.
slow = project("x_brutal.yaml" => "header: $stdout.puts(:started); $stdout.flush\nsubject: 'sleep %{a}'\n" \
                                  "contexts: {a: [30]}\nactuals: ['%{subject}']\n")
reader, writer = IO.pipe
errors, errors_writer = IO.pipe
pid = spawn(RbConfig.ruby, executable, slow, out: writer, err: errors_writer)
writer.close
errors_writer.close
raise unless reader.gets == "started\n"
Process.kill(:INT, pid)
_, status = Process.wait2(pid)
raise unless status.signaled? && status.termsig == Signal.list.fetch("INT")
written = errors.read
raise unless written.empty?

# A name that is not valid UTF-8, as ARGV gives it, is refused before the
# file is read (APFS would not even hold it).
raise unless failure(File.join(project({}), "a\xFF_brutal.yaml"))&.start_with?("the file name must be")

# A directory the file system names in another encoding, as it does under
# the C locale, is reported with a message in UTF-8, with a test file that
# fails under ruby, and by --check.
foreign = File.join(project({}), "café".b)
Dir.mkdir(foreign)
File.write(File.join(foreign, "x_brutal.yaml"),
           "subject: '%{v}'\ncontexts: {v: ['\"é\".encode(\"ISO-8859-1\")']}\nactuals: ['%{subject}']\n")
status, _, err = brutal(foreign)
raise unless status == 1 && err.b == "brutal: #{foreign}/x_brutal.yaml: ".b +
                                     "v = \"é\".encode(\"ISO-8859-1\"): actual is a String in ISO-8859-1, " \
                                     "which brutal cannot write as a literal\n".b
File.write(File.join(foreign, "x_brutal.yaml"), "subject: '[defined?(Brutal), %{n}]'\ncontexts: {n: [1]}\n" \
                                                "actuals: ['%{subject}']\n")
status, _, err = brutal(foreign)
raise unless status == 1 && err.b.include?("ruby runs it: #{foreign}/test_x.rb:".b) && !err.include?(".tmp")
status, _, err = brutal("--check", foreign)
raise unless status == 1 && err.b == "brutal: #{foreign}/x_brutal.yaml: #{foreign}/test_x.rb is missing\n".b
