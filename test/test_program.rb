# The program of a manifest, or the message of the error it raises.
def program(yaml)
  Brutal::Program.new(Brutal::Manifest.read(manifest(yaml)))
rescue Brutal::Error => e
  e.message
end

# Every combination of the contexts, in the order of the file, the first
# context varying the slowest.
combined = program("subject: '[%{b}, %{a}]'\ncontexts: {b: [1, 2], a: [x, y, z]}\nactuals: ['%{subject}', '1']\n")
raise unless combined.cases.map(&:values) == [%w[1 x], %w[1 y], %w[1 z], %w[2 x], %w[2 y], %w[2 z]]
raise unless combined.cases.first == { "b" => "1", "a" => "x" }
raise unless combined.size == 12
raise unless combined.frozen? && combined.cases.frozen? && combined.cases.first.frozen?

# The two forms have the same lines, but for the separators and the head of
# each assertion.
recording = combined.record.lines
test = combined.test(Array.new(12, &:to_s)).lines
raise unless recording.size == test.size
differences = recording.zip(test).reject { |a, b| a == b }
raise unless differences.size == 6 + 12
raise unless differences.first == ["$__brutal__.enter(0)\n", "# #{"-" * 78}\n"]
raise unless differences[1] == ["$__brutal__.observe((\n",
                                "::Kernel.raise \"b = 1, a = x: actual\" unless (0).eql?((\n"]
raise unless test.first == "# Generated by brutal from x_brutal.yaml: edit the manifest, then run brutal again.\n"
raise unless test.last == "))\n"
raise unless combined.test(Array.new(12, "nil")).include?("  [1, x]\nend\n")

# Placeholders: only %{name}, for a context, in the subject, and %{subject}
# in an actual; each context is used. Any other % is left as written.
percent = program(<<~YAML)
  subject: |-
    [%{n} % 3, "%05d" % %{n}, format("%<v>s", v: %{n}), %w[a b], %{n}, "%{other", "%%{n}"]
  contexts:
    n: [7]
  actuals:
    - "%{subject}.size % 2"
YAML
expected = '[7 % 3, "%05d" % 7, format("%<v>s", v: 7), %w[a b], 7, "%{other", "%7"]'
raise unless percent.test(["nil"]).include?("\n  #{expected}\nend\n")
raise unless percent.test(["nil"]).include?("\n  actual.size % 2\n))")
raise unless program("subject: '%{a} + %{b}'\ncontexts: {a: [1]}\nactuals: [x]\n") ==
             "the subject uses %{b}, which is not a context"
raise unless program("subject: '%{a}'\ncontexts: {a: [1], b: [2]}\nactuals: [x]\n") ==
             "the context b is not used in the subject"
raise unless program("subject: '%{a}'\ncontexts: {a: [1]}\nactuals: ['%{subject} + %{a}']\n") ==
             "an actual can only use %{subject}, not %{a}"

# Code of one line is indented; code of several lines is left as written,
# so that a multi-line string or a heredoc keeps its content.
nested = program(<<~YAML)
  subject: |
    <<~TEXT + %{a}
      first
    TEXT
  contexts:
    a: ['"x"']
  actuals:
    - |
      %{subject}
        .upcase
YAML
raise unless nested.test(["nil"]).include?("actual = begin\n<<~TEXT + \"x\"\n  first\nTEXT\nend\n")
raise unless nested.test(["nil"]).include?("unless (nil).eql?((\nactual\n  .upcase\n))\n")

# Sections appear once or once per example, in the order of the file.
sections = program(<<~YAML).test(%w[1 2])
  header: "# header"
  before: "# before"
  subject: "%{a}"
  contexts:
    a: [1, 2]
  actuals: ["%{subject}"]
  after: "# after"
  footer: "# footer"
YAML
raise unless sections.scan("# header").size == 1 && sections.scan("# footer").size == 1
raise unless sections.scan("# before").size == 2 && sections.scan("# after").size == 2
order = ["# header", "# before", "actual = begin", "(1).eql?", "# after", "# before", "(2).eql?", "# after", "# footer"]
order.inject(0) { |position, text| (sections.index(text, position) or raise "#{text} out of order") + 1 }
raise unless sections.end_with?("# footer\n")

