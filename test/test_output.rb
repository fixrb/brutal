# frozen_string_literal: true

require_relative File.join("support", "coverage")
require_relative File.join("..", "lib", "brutal")
require_relative File.join("support", "project")

# The message of the Brutal::Error raised by the write, or nil.
def refusal(path, source)
  Brutal::Output.write(path, source)
  nil
rescue Brutal::Error => e
  e.message
end

directory = project({})
source = "# Generated by brutal from x_brutal.yaml: edit the manifest, then run brutal again.\n"

# test_NAME.rb, next to NAME_brutal.yaml.
raise unless Brutal::Output.target("spec/models/user_brutal.yaml") == "spec/models/test_user.rb"
raise unless Brutal::Output.target("user_brutal.yaml") == "test_user.rb"
raise unless Brutal::Output.target("./user_brutal.yaml") == "./test_user.rb"
raise unless Brutal::Output.target("/tmp/my.user_brutal.yaml") == "/tmp/test_my.user.rb"

# A new file is written whole; an unchanged one is left untouched.
path = File.join(directory, "test_x.rb")
Brutal::Output.write(path, source)
raise unless File.binread(path) == source
raise unless Brutal::Output.current?(path, source)
File.utime(0, 0, path)
Brutal::Output.write(path, source)
raise unless File.mtime(path).to_i.zero?
Brutal::Output.write(path, "#{source}# more\n")
raise unless File.binread(path) == "#{source}# more\n"
raise unless Dir.children(directory) == ["test_x.rb"]

# Written as bytes, whatever the default encodings.
verbose = $VERBOSE
internal = Encoding.default_internal
begin
  $VERBOSE = nil
  Encoding.default_internal = Encoding::UTF_16LE
  Brutal::Output.write(path, "#{source}# caf\u00E9\n")
  raise unless File.binread(path) == "#{source}# caf\u00E9\n".b
ensure
  Encoding.default_internal = internal
  $VERBOSE = verbose
end

# A file brutal did not write is never replaced, nor anything but a file.
foreign = File.join(directory, "test_foreign.rb")
File.write(foreign, "# A test written by hand.\n")
raise unless refusal(foreign, source) == "#{foreign} was not written by brutal 2 (delete it once if brutal 1 wrote it)"
raise unless File.read(foreign) == "# A test written by hand.\n"
File.write(foreign, "")
raise unless refusal(foreign, source).start_with?("#{foreign} was not written by brutal 2")
raise unless refusal(directory, source) == "#{directory} is not a regular file"
outside = File.join(project({}), "dotfile")
File.write(outside, source)
link = File.join(directory, "test_link.rb")
File.symlink(outside, link)
raise unless refusal(link, source) == "#{link} is a symbolic link"
raise if Brutal::Output.current?(link, source)
dangling = File.join(directory, "test_dangling.rb")
File.symlink(File.join(directory, "missing"), dangling)
raise unless refusal(dangling, source) == "#{dangling} is a symbolic link"
raise if File.exist?(File.join(directory, "missing"))
raise unless File.binread(outside) == source

# A write that fails leaves the old file and no temporary file.
blocked = File.join(directory, "test_blocked.rb")
Brutal::Output.write(blocked, source)
temporary = File.join(directory, ".test_blocked.rb.#{Process.pid}.tmp")
File.write(temporary, "stale")
begin
  Brutal::Output.write(blocked, "#{source}# new\n")
  raise "expected Errno::EEXIST"
rescue Errno::EEXIST
  raise unless File.binread(blocked) == source && File.read(temporary) == "stale"
end
File.delete(temporary)
failing = false
File.singleton_class.prepend(Module.new do
  define_method(:rename) do |*names|
    failing ? raise(Errno::EXDEV) : super(*names)
  end
end)
begin
  failing = true
  Brutal::Output.write(blocked, "#{source}# new\n")
  raise "expected Errno::EXDEV"
rescue Errno::EXDEV
  raise unless File.binread(blocked) == source
  raise if File.exist?(temporary)
ensure
  failing = false
end
Brutal::Output.write(blocked, "#{source}# new\n")
raise unless File.binread(blocked) == "#{source}# new\n"

# A new file gets the default mode; a replaced file keeps its own.
fresh = File.join(project({}), "test_fresh.rb")
Brutal::Output.write(fresh, source)
raise unless File.stat(fresh).mode & 0o7777 == 0o666 & ~File.umask
File.chmod(0o750, fresh)
Brutal::Output.write(fresh, "#{source}# changed\n")
raise unless File.stat(fresh).mode & 0o7777 == 0o750 && File.read(fresh).end_with?("# changed\n")

# The block receives the temporary file before it replaces the old one, or
# the unchanged file; a block that raises leaves the old file, and no
# temporary file.
handed = nil
Brutal::Output.write(fresh, File.read(fresh)) { |file| handed = file }
raise unless handed == fresh
seen = nil
Brutal::Output.write(fresh, "#{source}# seen\n") { |temporary| seen = File.read(temporary) }
raise unless seen == "#{source}# seen\n" && File.read(fresh) == seen
begin
  Brutal::Output.write(fresh, "#{source}# refused\n") { |_temporary| raise Brutal::Error, "no" }
  raise "expected Brutal::Error"
rescue Brutal::Error => e
  raise unless e.message == "no" && File.read(fresh) == seen
  raise unless Dir.children(File.dirname(fresh)) == ["test_fresh.rb"]
end

# The source is synced before the rename.
synced = 0
File.prepend(Module.new do
  define_method(:fsync) do
    synced += 1
    super()
  end
end)
Brutal::Output.write(fresh, "#{source}# synced\n")
raise unless synced == 1

# A write that fails after the temporary file was created removes it.
failing = false
File.prepend(Module.new { define_method(:write) { |*text| failing ? raise(Errno::ENOSPC) : super(*text) } })
begin
  failing = true
  Brutal::Output.write(fresh, "#{source}# full\n")
  raise "expected Errno::ENOSPC"
rescue Errno::ENOSPC
  raise unless File.read(fresh) == "#{source}# synced\n"
  raise unless Dir.children(File.dirname(fresh)) == ["test_fresh.rb"]
ensure
  failing = false
end
